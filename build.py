def jsonld_book(book, lang, L):
    data = {
        "@context": "https://schema.org",
        "@type": "Book",
        "name": L["title"],
        "author": {"@type": "Person", "name": byline_name(byline_key(book), "en")},
        "publisher": {"@type": "Organization", "name": SITE["site_name"]},
        "inLanguage": lang,
        "url": canonical(page_path(lang, "book", book["slug"])),
        "image": og_image_for(book),
    }
    if book["isbn"]:
        data["isbn"] = book["isbn"]
    if book["pages"]:
        data["numberOfPages"] = int(book["pages"])
    # The exact date outranks the bare year when both are known. No row
    # carries a year today, so in practice this is the release date or nothing.
    if book.get("release_date") or book["year"]:
        data["datePublished"] = (book.get("release_date") or "").strip() or book["year"]
    if book["series"]:
        data["isPartOf"] = {"@type": "BookSeries", "name": book["series"]}
        if book["series_order"]:
            data["position"] = int(book["series_order"])
    avail = {"published": "https://schema.org/InStock",
             "preorder": "https://schema.org/PreOrder"}.get(book["status"])
    if avail:
        offers = [{"@type": "Offer", "url": r["url"], "availability": avail}
                  for r in links_for(book["id"], lang)]
        if offers:
            data["offers"] = offers
    return ('<script type="application/ld+json">'
            + json.dumps(data, ensure_ascii=False) + "</script>\n")


