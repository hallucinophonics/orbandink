def privacy_paragraphs(lang):
    row = PRIVACY.get(lang) or PRIVACY.get("en") or {}
    paras = [p.strip() for p in re.split(r"\n\s*\n", row.get("body", "")) if p.strip()]
    return "\n".join(f"      <p>{esc(p)}</p>" for p in paras)


def socials(fmt):
    out = []
    for key, val in SITE.items():
        # seed rows keep PLACEHOLDER urls — a link that goes nowhere never ships
        if key.startswith("social_") and not any(
                tok in val for tok in ("PLACEHOLDER", "example.com", "TODO")):
            label = key.split("_", 1)[1].replace("_", ".").title()
            out.append(fmt.format(url=esc(val), label=esc(label)))
    return "\n".join(out) + "\n"


def lang_links(lang, kind, rel, slug=None):
    panel, foot = [], []
    for l in LANGS:
        code = l["code"]
        cur = ' aria-current="true"' if code == lang else ""
        path = rel + page_path(code, kind, slug)
        panel.append(f'      <a href="{path}" lang="{code}" hreflang="{code}"{cur}>'
                     f'<span class="lc">{esc(l["short"])}</span>{esc(l["native"])}</a>')
        foot.append(f'      <a href="{path}" lang="{code}" hreflang="{code}"{cur}>{code}</a>')
    sep = '<span class="sep" aria-hidden="true">/</span>'
    return "\n".join(panel) + "\n", ("\n" + sep + "\n").join(foot) + "\n"


