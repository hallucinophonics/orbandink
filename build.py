def build_root():
    write("index.html", render("root_redirect", {
        "SITE_NAME": esc(SITE["site_name"]),
        "DOMAIN": DOMAIN,
    }))

    blocks = []
    for l in LANGS:
        code = l["code"]
        hidden = "" if code == "en" else " hidden"
        blocks.append(
            f'<div class="nf" data-nf="{code}"{hidden}>\n'
            f'  <p class="kicker">{esc(SITE["site_name"])}</p>\n'
            f'  <div class="nf-code" aria-hidden="true">404</div>\n'
            f'  <p class="msg">{esc(t("nf.body", code))}</p>\n'
            f'  <a class="btn" href="/{code}/" data-home="{code}">{esc(t("nf.back", code))}</a>\n'
            f'</div>')
    write("404.html", render("404", {
        "SITE_NAME": esc(SITE["site_name"]),
        "LANGS": ",".join(CODES),
        "NF_BLOCKS": "\n".join(blocks),
    }))

    write("_redirects", "\n".join([
        "# generated by build.py",
        "/ /en/ 302",
        "/books /en/books/ 302",
        "/series /en/series/ 302",
        "/about /en/about/ 302",
        "/privacy /en/privacy/ 302",
    ]) + "\n")

    write("robots.txt",
          f"User-agent: *\nAllow: /\n\nSitemap: https://{DOMAIN}/sitemap.xml\n")

    urls = []
    for kind, slug_list in (("home", [None]), ("books", [None]),
                            ("book", [b["slug"] for b in BOOKS]),
                            ("worlds", [None]),
                            ("world", [r["slug"] for r in listed_series()]),
                            ("about", [None]), ("privacy", [None])):
        for slug in slug_list:
            for code in CODES:
                alts = "".join(
                    f'\n    <xhtml:link rel="alternate" hreflang="{c}" href="{canonical(page_path(c, kind, slug))}"/>'
                    for c in CODES)
                alts += f'\n    <xhtml:link rel="alternate" hreflang="x-default" href="{canonical(page_path("en", kind, slug))}"/>'
                urls.append(f'  <url>\n    <loc>{canonical(page_path(code, kind, slug))}</loc>{alts}\n  </url>')
    write("sitemap.xml",
          '<?xml version="1.0" encoding="UTF-8"?>\n'
          '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" '
          'xmlns:xhtml="http://www.w3.org/1999/xhtml">\n'
          + "\n".join(urls) + "\n</urlset>\n")


# ---------------------------------------------------------------- images (optional)

def build_images():
    try:
        from PIL import Image  # type: ignore
    except ImportError:
        print("  · Pillow not installed — skipping responsive covers + OG images "
              "(pages fall back to the base cover; install Pillow and re-run to upgrade)")
        return
    for book in ALL_BOOKS:
        src = ROOT / book["cover"]
        if not src.exists():
            warn(f"cover missing: {book['cover']}")
            continue
        img = Image.open(src).convert("RGB")
        for w in (480, 800):
            out = ROOT / f"covers/{Path(book['cover']).stem}-{w}.jpg"
            # Written only when ABSENT until now, so replacing a source cover
            # left the -480/-800 showing the old art indefinitely: the shelf's
            # real covers landed in covers/<id>.jpg while the responsive
            # variants stayed on July's placeholders. Rebuild when the source
            # is newer, like any build system.
            if not out.exists() or src.stat().st_mtime > out.stat().st_mtime:
                r = img.copy()
                r.thumbnail((w, w * 2))
                r.save(out, "JPEG", quality=82)
        og_path = ROOT / f"og/{book['id']}.jpg"
        og_path.parent.mkdir(exist_ok=True)
        og = Image.new("RGB", (1200, 630), "#0A0908")
        cov = img.copy()
        cov.thumbnail((10_000, 530))
        og.paste(cov, (60, 50))
        bar = Image.new("RGB", (10, 530), book["accent"] or SITE["accent"])
        og.paste(bar, (60 + cov.width + 24, 50))
        og.save(og_path, "JPEG", quality=85)
    print("  · Pillow found — responsive covers + OG images written")


# ---------------------------------------------------------------- validation

def validate():
    slugs = [b["slug"] for b in BOOKS]
    if len(slugs) != len(set(slugs)):
        sys.exit("FATAL: duplicate slugs in books.csv")
    for b in BOOKS:
        if not any(r["book_id"] == b["id"] and r["lang"] == "en" for r in BI18N):
            sys.exit(f"FATAL: {b['id']} has no en row in books_i18n.csv")
        if not (ROOT / b["cover"]).exists():
            warn(f"cover file missing: {b['cover']}")
        for code in CODES:
            if not any(r["book_id"] == b["id"] and r["lang"] == code for r in BI18N):
                print(f"  · note: {b['id']} has no {code} translation — en fallback in use")
    for key, row in I18N.items():
        for code in CODES:
            if not row.get(code):
                print(f"  · note: i18n {key} missing {code} — en fallback in use")


# ---------------------------------------------------------------- main

def main():
    if "--clean" in sys.argv:
        for code in CODES:
            shutil.rmtree(ROOT / code, ignore_errors=True)
        print("cleaned /{lang}/ trees")
    print(f"build — {len(BOOKS)} books × {len(CODES)} languages")
    validate()
    build_images()
    for code in CODES:
        build_home(code)
        build_books(code)
        for book in BOOKS:
            build_book(code, book)
        build_worlds(code)
        for row in listed_series():
            build_world(code, row)
        build_about(code)
        build_privacy(code)
    build_root()
    print(f"wrote {len(written)} files"
          + (f" · {len(warnings)} warning(s)" if warnings else ""))


if __name__ == "__main__":
    main()
