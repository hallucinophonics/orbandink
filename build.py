#!/usr/bin/env python3
"""
build.py — static site generator for orbandink.co.uk
------------------------------------------------------
The Orb & Ink publisher storefront: the imprint's catalogue and its
authors, prerendered for every language from data/*.csv + templates/.
Python 3 stdlib only. Pillow is OPTIONAL — when installed it also makes
responsive cover sizes (covers/{id}-480.jpg / -800.jpg) and OG images
(og/{id}.jpg); without it those steps are skipped gracefully.

    python3 build.py            # regenerate everything (idempotent)
    python3 build.py --clean    # remove generated /{lang}/ trees first

OUTPUT (committed to the repo; never hand-edit):
    /{lang}/…/index.html   for en ru fr pt de it es ja
    index.html  404.html  _redirects  robots.txt  sitemap.xml
"""
import csv
import datetime
import html
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
GENERATED_MARK = "<!-- generated by build.py — do not edit -->"

# ---------------------------------------------------------------- data


def read_csv(name):
    with open(ROOT / "data" / f"{name}.csv", encoding="utf-8-sig", newline="") as f:
        return [{k.strip(): (v or "").strip() for k, v in row.items()}
                for row in csv.DictReader(f)]


LANGS = read_csv("languages")                      # keeps CSV order
CODES = [l["code"] for l in LANGS]
SITE = {r["key"]: r["value"] for r in read_csv("site")}
I18N = {r["key"]: r for r in read_csv("i18n")}
BOOKS = read_csv("books")
# Every row, whatever its status. Derived assets (responsive covers, OG) are
# not publication — generating them for a coming-soon book reveals nothing and
# means flipping catalog_coming_soon later needs no second build.
ALL_BOOKS = list(BOOKS)
# catalog_coming_soon (data/site.csv): "show" keeps unreleased books in the
# catalogue wearing their Coming soon pill — the full-shelf storefront view.
# "hide" builds a published-only site for when the imprint wants to promote
# nothing before its time. One switch, no row edits.
if SITE.get("catalog_coming_soon", "show") == "hide":
    BOOKS = [b for b in BOOKS if b["status"] in ("published", "preorder")]
BI18N = read_csv("books_i18n")
LINKS = read_csv("store_links")
PRIVACY = {r["lang"]: r for r in read_csv("privacy_i18n")}
# Some series have a dedicated world-site (hand-owned data/series.csv);
# PLACEHOLDER urls stay hidden until the real domain exists.
SERIES_SITES = {r["series"]: r["url"] for r in read_csv("series")
                if r["url"] and not any(tok in r["url"] for tok in
                                        ("PLACEHOLDER", "example.com", "TODO"))}
# A series may brand its ordinal (The Universal Menu numbers its books as
# menu courses); the label lives in i18n so every language uses its own
# restaurant word (Gang, Service, Portata…). Empty key → plain number.
SERIES_ORDINAL = {r["series"]: r.get("ordinal_key", "") for r in read_csv("series")}


def series_no(book, lang):
    """The series-branded ordinal: 'Course 01' / 'Gang 01' / plain '01'."""
    n = f'{int(book["series_order"]):02d}'
    key = SERIES_ORDINAL.get(book["series"], "")
    return f'{t(key, lang)} {n}' if key else n
PRAISE = read_csv("praise")

DOMAIN = SITE["domain"]
YEAR = datetime.date.today().year
FORMAT_ORDER = ["ebook", "paperback", "hardcover", "audiobook"]
OG_LOCALE = {"en": "en_US", "ru": "ru_RU", "fr": "fr_FR", "pt": "pt_PT",
             "de": "de_DE", "it": "it_IT", "es": "es_ES", "ja": "ja_JP"}
warnings = []


def warn(msg):
    warnings.append(msg)
    print(f"  ⚠ {msg}")


def t(key, lang, **vars):
    row = I18N.get(key)
    if not row:
        warn(f"i18n key missing: {key}")
        return key
    s = row.get(lang) or row.get("en") or key
    for k, v in vars.items():
        s = s.replace("{%s}" % k, str(v))
    return s


def esc(s):
    return html.escape(str(s), quote=True)


def loc(book, lang):
    """Localized fields for a book; missing language rows fall back to en."""
    mine = next((r for r in BI18N if r["book_id"] == book["id"] and r["lang"] == lang), None)
    en = next((r for r in BI18N if r["book_id"] == book["id"] and r["lang"] == "en"), None)
    row = mine or en or {}
    return {
        "title": row.get("title") or book["id"],
        "tagline": row.get("tagline", ""),
        "synopsis": row.get("synopsis", ""),
        "excerpt_url": row.get("excerpt_url", ""),
    }


def links_for(book_id, lang):
    rows = [r for r in LINKS if r["book_id"] == book_id]
    mine = [r for r in rows if r["lang"] == lang]
    return mine if mine else [r for r in rows if r["lang"] == "en"]


def praise_for(book_id, lang):
    rows = [r for r in PRAISE if r["book_id"] == book_id]
    mine = [r for r in rows if r["lang"] == lang]
    return mine if mine else [r for r in rows if r["lang"] == "en"]


def themes_of(book):
    return [s.strip() for s in book["themes"].split(";") if s.strip()]


def theme_key(tok):
    return "theme." + re.sub(r"[\s\-]+", "_", tok)


# ---------------------------------------------------------------- urls

def page_path(lang, kind, slug=None):
    return {"home": f"{lang}/", "books": f"{lang}/books/",
            "book": f"{lang}/books/{slug}/", "about": f"{lang}/about/",
            "privacy": f"{lang}/privacy/"}[kind]


def canonical(path):
    return f"https://{DOMAIN}/{path}"


def hreflangs(kind, slug=None):
    out = []
    for code in CODES:
        out.append(f'<link rel="alternate" hreflang="{code}" href="{canonical(page_path(code, kind, slug))}">')
    out.append(f'<link rel="alternate" hreflang="x-default" href="{canonical(page_path("en", kind, slug))}">')
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- templates

TPL = {p.stem: p.read_text(encoding="utf-8")
       for p in (ROOT / "templates").glob("*.html")}
TOKEN = re.compile(r"\{\{([A-Z0-9_]+)\}\}")


def render(tpl_name, mapping):
    def sub(m):
        key = m.group(1)
        if key not in mapping:
            raise KeyError(f"template {tpl_name}: unmapped token {{{{{key}}}}}")
        return str(mapping[key])
    return TOKEN.sub(sub, TPL[tpl_name])


written = []


def write(path, content):
    p = ROOT / path
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(content, encoding="utf-8")
    written.append(path)


# ---------------------------------------------------------------- fragments

def srcset_for(cover, rel):
    """Only reference responsive sizes that actually exist on disk."""
    stem = Path(cover).stem
    variants = [(w, f"{rel}covers/{stem}-{w}.jpg") for w in (480, 800)
                if (ROOT / f"covers/{stem}-{w}.jpg").exists()]
    if not variants:
        return ""
    srcset = ", ".join(f"{p} {w}w" for w, p in variants)
    return f' srcset="{srcset}" sizes="(max-width: 900px) 90vw, 420px"'


def og_image_for(book):
    og = f"og/{book['id']}.jpg"
    return canonical(og if (ROOT / og).exists() else book["cover"])


def preloads(lang, rel):
    """Preload only the active language's font subsets — only files that exist."""
    fonts = ROOT / "assets" / "fonts"
    if not fonts.is_dir():
        return ""
    want = []
    if lang != "ja":
        for fam in ("unbounded", "playfair-display", "manrope", "jetbrains-mono"):
            for w in ("400", "700"):
                want.append(f"{fam}-{w}-latin.woff2")
        if lang == "ru":
            for fam in ("unbounded", "playfair-display", "manrope", "jetbrains-mono"):
                want.append(f"{fam}-700-cyrillic.woff2")
                want.append(f"{fam}-400-cyrillic.woff2")
    out = []
    for name in want:
        if (fonts / name).exists() and len(out) < 8:
            out.append(f'<link rel="preload" href="{rel}assets/fonts/{name}" as="font" type="font/woff2" crossorigin>')
    return ("\n".join(out) + "\n") if out else ""


def status_pill(book, lang):
    if book["status"] == "preorder":
        return f' <span class="pill pill--preorder">{esc(t("status.preorder", lang))}</span>'
    if book["status"] == "coming_soon":
        return f' <span class="pill pill--soon">{esc(t("status.coming_soon", lang))}</span>'
    return ""


def cta_key(status):
    return {"published": "book.buy", "preorder": "book.preorder",
            "coming_soon": "book.coming_soon"}.get(status, "book.buy")


def plate_attr(book):
    """Interim plates (no real cover art yet) keep the rained-in title and
    never run the reveal — there is nothing truer underneath to show."""
    return ' data-plate="1"' if book.get("cover_art") == "plate" else ""


def card(book, lang, rel):
    L = loc(book, lang)
    return render("_card", {
        "REL": rel,
        "C_IDX": f"{BOOKS.index(book) + 1:02d}",
        "C_ACCENT": book["accent"] or SITE["accent"],
        "C_SERIES": esc(book["series"]),
        "C_THEMES": esc(book["themes"]),
        "C_SLUG": book["slug"],
        "C_PLATE": plate_attr(book),
        "C_ID": book["id"],
        "C_COVER": book["cover"],
        "C_SRCSET": srcset_for(book["cover"], rel),
        "C_ALT": esc(L["title"]),
        "C_YEAR": esc(book["year"]),
        "C_META_RIGHT": esc(book["series"] or t("book.standalone", lang)),
        "C_TITLE": esc(L["title"]),
        "C_TAGLINE": esc(L["tagline"]),
        "LANG": lang,
    })


def glyph_pool():
    """Characters the hero lattice is built from: the bylines and book titles
    across scripts + digits/timestamps/binary. Byline glyphs go in first so
    every script the name rotation reaches survives the 96-glyph cap."""
    chars = []
    for key in ("hero.word", "hero.word.bianco",
                "hero.word.weiss", "hero.word.blanc"):
        for code in ("en", "ru", "ja"):
            chars.extend(t(key, code).replace("|", ""))
    for r in BI18N:
        if r["lang"] in ("en", "ru", "ja"):
            chars.extend(r["title"])
    seen = []
    for c in chars:
        if c.strip() and c not in seen:
            seen.append(c)
    return "".join(seen[:96]) + "0123456789:/·—"


def hero_words(lang):
    """The hero lattice's morph frames: all four of the house's bylines — the
    real name and the three pen names — rotating through the en/ru/ja scripts,
    stepped together (4 and 3 are coprime, so all twelve name×script frames
    occur and consecutive frames change both). The page's own script leads so
    the first frame matches the static H1 underneath the canvas."""
    identities = ["hero.word", "hero.word.bianco",
                  "hero.word.weiss", "hero.word.blanc"]
    scripts = ["en", "ru", "ja"]
    if lang in scripts:
        scripts = [lang] + [s for s in scripts if s != lang]
    frames = []
    for i in range(len(identities) * len(scripts)):
        word = t(identities[i % len(identities)], scripts[i % len(scripts)])
        word = word.replace("|", "\n")
        if word not in frames:
            frames.append(word)
    return json.dumps(frames, ensure_ascii=False)


def ticker_html(lang):
    """One ticker segment: localized themes + series names, CSV order."""
    items = []
    for b in BOOKS:
        for tok in themes_of(b):
            lbl = t(theme_key(tok), lang)
            if lbl not in items:
                items.append(lbl)
    for b in BOOKS:
        if b["series"] and b["series"] not in items:
            items.append(b["series"])
    out = []
    for it in items:
        out.append(f'<span class="ti">{esc(it)}</span><span class="tsep">·</span>')
    return "".join(out)


def book_years():
    return sorted({int(b["year"]) for b in BOOKS if b["year"]})


def timeline_html(accent_year=None):
    nodes = []
    for y in book_years():
        cls = " acc" if (accent_year is not None and y == accent_year) else ""
        nodes.append(f'    <span class="tl-node{cls}"><i></i>{y}</span>')
    return "\n".join(nodes)


def cat_span():
    ys = book_years()
    return f"{ys[0]} — {ys[-1]}" if ys else ""


# Month names per language, so a release date reads as written rather than as
# an ISO string. Locale-aware formatting is deliberately not used: the build
# must produce identical bytes on any machine, and the C library's locale set
# is not something a static site can depend on.
MONTHS = {
    "en": "January February March April May June July August September October November December",
    "ru": "января февраля марта апреля мая июня июля августа сентября октября ноября декабря",
    "fr": "janvier février mars avril mai juin juillet août septembre octobre novembre décembre",
    "pt": "janeiro fevereiro março abril maio junho julho agosto setembro outubro novembro dezembro",
    "de": "Januar Februar März April Mai Juni Juli August September Oktober November Dezember",
    "it": "gennaio febbraio marzo aprile maggio giugno luglio agosto settembre ottobre novembre dicembre",
    "es": "enero febrero marzo abril mayo junio julio agosto septiembre octubre noviembre diciembre",
}


def release_date(book, lang):
    """A book's release date written the way that language writes one.

    Empty until the owner sets it, which is the normal state for an
    unannounced book: no date is better than a guessed one, so a missing
    value simply drops the row rather than inventing "TBC".
    """
    raw = (book.get("release_date") or "").strip()
    if not raw:
        return ""
    try:
        y, m, d = (int(x) for x in raw.split("-"))
        month = MONTHS.get(lang, MONTHS["en"]).split()[m - 1]
    except (ValueError, IndexError):
        return raw           # malformed dates surface as themselves, not as a crash
    if lang == "ja":
        return f"{y}年{m}月{d}日"
    if lang == "ru":
        return f"{d} {month} {y}"          # month already genitive
    if lang in ("pt", "es"):
        return f"{d} de {month} de {y}"
    if lang == "de":
        return f"{d}. {month} {y}"
    if lang == "fr":
        return f"{'1er' if d == 1 else d} {month} {y}"
    if lang == "it":
        return f"{'1º' if d == 1 else d} {month} {y}"
    return f"{d} {month} {y}"


def foot_status(lang):
    return (f'{esc(t("nav.books", lang))} {len(BOOKS):02d} · '
            f'{esc(t("a11y.langs", lang))} {len(LANGS):02d} · '
            f'<span class="ok">{esc(t("footer.status", lang))}</span>')


def f_data(book, lang):
    parts = []
    if book["year"]:
        parts.append(esc(book["year"]))
    parts.append(esc(f'{book["series"]} {series_no(book, lang)}'
                     if book["series"] else t("book.standalone", lang)))
    parts.append(esc(t("status." + book["status"], lang)))
    if book["pages"]:
        parts.append(esc(f'{book["pages"]} {t("plate.pages", lang)}'))
    return "\n".join(f'        <span class="ds">{p}</span>' for p in parts)


